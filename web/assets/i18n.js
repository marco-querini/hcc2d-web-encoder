export const MESSAGES = Object.freeze({ en, es, it, ja, "zh-hans": zhHans });

let currentLocale = "en";

export function normalizeLocale(value) {
  const candidate = String(value || "").toLowerCase();
  if (candidate.startsWith("zh")) return "zh-hans";
  const short = candidate.split("-")[0];
  return Object.hasOwn(MESSAGES, candidate) ? candidate : (Object.hasOwn(MESSAGES, short) ? short : "en");
}

export function setLocale(value) {
  currentLocale = normalizeLocale(value);
  return currentLocale;
}

export function getLocale() {
  return currentLocale;
}

export function t(key, values = {}) {
  const template = MESSAGES[currentLocale]?.[key] ?? en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? `{${name}}`));
}

export function translateDocument(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((element) => { element.textContent = t(element.dataset.i18n); });
  for (const [attribute, selector] of [
    ["aria-label", "data-i18n-aria-label"],
    ["placeholder", "data-i18n-placeholder"],
    ["title", "data-i18n-title"],
    ["alt", "data-i18n-alt"]
  ]) {
    root.querySelectorAll(`[${selector}]`).forEach((element) => element.setAttribute(attribute, t(element.getAttribute(selector))));
  }
  document.documentElement.lang = LOCALES.find((locale) => locale.code === currentLocale)?.htmlLang || "en";
  document.title = t("meta.title");
  document.querySelector('meta[name="description"]')?.setAttribute("content", t("meta.description"));
}
